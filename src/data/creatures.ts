export const SPECIES_BY_ID: ReadonlyMap<string, Species> = new Map(SPECIES.map((s) => [s.id, s]));

export function speciesForBiome(biome: Species['biome']): readonly Species[] {
  return SPECIES.filter((s) => s.biome === biome);
}

export function requireSpecies(id: string): Species {
  const s = SPECIES_BY_ID.get(id);
  if (!s) throw new Error(`Unknown species: ${id}`);
  return s;
}
